//! Exhaustive field classification for the startup wiring test.
use super::*;

// Each field occurs in exactly one category. The pattern deliberately has no
// rest pattern: adding an App field must make a classification decision here.
// Pool references and the exhaustive pattern come from the same field lists.
macro_rules! configured_pools {
    ($app:expr;
        required: [$($required:ident),* $(,)?],
        optional: [$($optional:ident),* $(,)?],
        arrays: [$($array:ident),* $(,)?],
        nested: [$($nested:ident),* $(,)?],
        optional_nested: [$($optional_nested:ident),* $(,)?],
        other: [$($other:ident),* $(,)?] $(,)?
    ) => {{
        let App {
            $($required,)* $($optional,)* $($array,)* $($nested,)*
            $($optional_nested,)* $($other: _,)*
        } = $app;
        let mut pools: Vec<(&'static str, &Arc<Pool>)> = vec![
            $((stringify!($required), $required),)*
            $((stringify!($optional), $optional.as_ref().expect(
                concat!(stringify!($optional), " configured")
            )),)*
        ];
        $(for pool in $array {
            pools.push((stringify!($array), pool.as_ref().expect(
                concat!(stringify!($array), " configured")
            )));
        })*
        $(for pool in $nested.startup_pools() {
            pools.push((stringify!($nested), pool));
        })*
        $(for pool in $optional_nested.as_ref().expect(
            concat!(stringify!($optional_nested), " configured")
        ).startup_pools() {
            pools.push((stringify!($optional_nested), pool));
        })*
        pools
    }};
}

