#!/usr/bin/env python3
"""Build the first-deploy catalog report by inlining the adoption SQL helpers.

No database connection. --check compares bytes without changing any files.
The generated script executes in a read-only transaction, with no temp objects.
"""
import argparse
import hashlib
from pathlib import Path
import re

MIG = Path(__file__).resolve().parents[1] / "postgres/migrations"


def tokens(sql):
    # All helper/adoption sources use ordinary quoted strings, comments and $$.
    return re.findall(r"--[^\n]*|/\*[\s\S]*?\*/|'(?:''|[^'])*'|[A-Za-z_][A-Za-z_0-9]*|\s+|.", sql)


def substitute(sql, arguments):
    return ''.join('(' + arguments[t] + ')' if t in arguments else t for t in tokens(sql))


def helpers(source):
    result = {}
    pattern = r'CREATE FUNCTION pg_temp\.(\w+)\((.*?)\)\s*RETURNS boolean LANGUAGE sql AS \$\$(.*?)\$\$;'
    for name, signature, body in re.findall(pattern, source, re.S):
        params = []
        for part in signature.split(','):
            bits = part.strip().split()
            params.append((bits[0], bits[3] if len(bits) == 4 and bits[2] == 'DEFAULT' else None))
        result[name] = (params, body.strip().removesuffix(';'))
    assert len(result) == 6, 'review changed helper source before regenerating'
    return result


def inline(query, definitions):
    ts = tokens(query)
    out = []
    i = 0
    while i < len(ts):
        if ts[i] != 'pg_temp':
            out.append(ts[i]); i += 1; continue
        assert ts[i+1] == '.' and ts[i+2] in definitions and ts[i+3] == '('
        name = ts[i+2]
        i += 4
        depth = 1
        args = ['']
        while depth:
            token = ts[i]; i += 1
            if token == '(':
                depth += 1
            elif token == ')':
                depth -= 1
                if not depth:
                    break
            if token == ',' and depth == 1:
                args.append('')
            else:
                args[-1] += token
        params, body = definitions[name]
        assert len(args) <= len(params)
        values = {}
        for index, (param, default) in enumerate(params):
            value = args[index].strip() if index < len(args) else default
            assert value is not None
            values[param] = value
        out.append('(' + substitute(body, values) + ')')
    return ''.join(out)


def build():
    source = (MIG/'adoption/helpers.sql').read_text()
    definitions = helpers(source)
    files = sorted((MIG/'adoption').glob('0*.sql'))
    def manifest(path):
        lines = [s for s in path.read_text().splitlines() if s and not s.startswith('#')]
        assert len(lines) == len(set(lines)), 'duplicate manifest entry'
        assert all(re.fullmatch(r'\d{6}_[A-Za-z0-9_]+\.sql', s) for s in lines)
        return set(lines)
    selected = manifest(MIG/'release.txt')
    held = manifest(MIG/'held.txt')
    pending = {'000019_create_polis_queue.sql', '000023_create_delphi_foundation.sql',
               '000024_create_polis_queue_large_class.sql', '000027_create_sealed_job_graphs.sql'}
    assert selected == {p.name for p in files} | pending, 'report scope differs from release selection'
    assert held == {'000021_create_polis_coordinator.sql'}, 'review changed hold policy'
    numbered = sorted(MIG.glob('*.sql'))
    assert all(re.fullmatch(r'\d{6}_[A-Za-z0-9_]+\.sql', p.name) for p in numbered), 'invalid numbered source name'
    assert len({p.name[:6] for p in numbered}) == len(numbered), 'duplicate migration number'
    assert {p.name for p in numbered} == selected | held, 'unclassified/missing numbered SQL'
    assert all(p.is_file() and not p.is_symlink() for p in numbered), 'nonregular numbered source'
    bindings = [MIG/'adoption/helpers.sql', MIG/'release.txt', MIG/'held.txt'] + files + numbered
    header = ['-- GENERATED by server/bin/build-migration-report.py; do not edit.',
              '-- First deployment only: no existing ledger or queue. Other states refuse.',
              '-- This is a catalog forecast, not DDL success or deployment-health proof.']
    for path in bindings:
        header.append('-- sha256 ' + hashlib.sha256(path.read_bytes()).hexdigest() + ' ' + str(path.relative_to(MIG)))
    # Each original predicate remains a scalar subquery. SQL helpers are inlined,
    # never installed, and role/catalog identity fields never leave the database.
    rows = []
    for path in files:
        rows.append("SELECT '"+path.name+"'::text AS migration, ("+inline(path.read_text().strip().removesuffix(';'), definitions)+") AS catalog_match")
    checks = '\nUNION ALL\n'.join(rows)
    return '\n'.join(header)+'''\nBEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY;
SET LOCAL search_path=pg_catalog,public;
SET LOCAL statement_timeout='30s';
SET LOCAL lock_timeout='2s';
WITH checks AS (
'''+checks+'''
), scope AS (
 SELECT to_regclass('public.migrations') IS NULL
    AND to_regclass('public.schema_migrations') IS NULL
    AND NOT EXISTS (SELECT 1 FROM pg_class WHERE relnamespace='public'::regnamespace
      AND (starts_with(relname,'polis_queue_') OR starts_with(relname,'delphi_')))
    AND NOT EXISTS (SELECT 1 FROM pg_proc WHERE pronamespace='public'::regnamespace
      AND (starts_with(proname,'pq_') OR starts_with(proname,'pd_'))) AS initial_state
), authority AS (
 SELECT
   has_database_privilege(current_user,current_database(),'TEMP')
     AND has_schema_privilege(current_user,'public','USAGE')
     AND has_schema_privilege(current_user,'public','CREATE') AS reconcile_authority,
   EXISTS (SELECT 1 FROM pg_roles WHERE rolname=current_user AND (rolsuper OR rolcreaterole)) AS create_roles,
   NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN ('polis_queue_owner','polis_queue_executor')) AS queue_roles_absent,
   has_schema_privilege(current_user,'public','USAGE WITH GRANT OPTION')
     AND has_schema_privilege(current_user,'public','CREATE WITH GRANT OPTION') AS schema_grants,
   EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
     WHERE n.nspname='public' AND c.relname='conversations'
     AND has_table_privilege(current_user,c.oid,'SELECT WITH GRANT OPTION')
     AND has_column_privilege(current_user,c.oid,'topic','UPDATE WITH GRANT OPTION')
     AND has_column_privilege(current_user,c.oid,'zid','REFERENCES WITH GRANT OPTION')) AS table_grants
), readiness AS (
 SELECT initial_state AND (SELECT bool_and(catalog_match) FROM checks)
     AND current_setting('server_version_num')::integer >= 170000 AS can_reconcile,
     create_roles AND queue_roles_absent AND schema_grants AND table_grants AS can_provision,
     initial_state, reconcile_authority, create_roles, queue_roles_absent, schema_grants, table_grants
 FROM scope CROSS JOIN authority
), output AS (
 SELECT migration, catalog_match,
   CASE WHEN NOT initial_state THEN 'REVIEW_EXISTING_LEDGER_OR_QUEUE'
        WHEN NOT catalog_match THEN 'CATALOG_MISMATCH'
        WHEN NOT can_reconcile THEN 'BLOCKED_BY_OTHER_CATALOG_CHECK'
        WHEN NOT reconcile_authority THEN 'REVIEW_MIGRATION_SESSION_AUTHORITY'
        ELSE 'WOULD_ADOPT' END AS outcome
 FROM checks CROSS JOIN readiness
 UNION ALL
 SELECT migration, NULL::boolean,
   CASE WHEN NOT can_reconcile THEN 'BLOCKED_RECONCILIATION'
        WHEN NOT reconcile_authority OR NOT can_provision THEN 'REVIEW_MIGRATION_SESSION_AUTHORITY'
        ELSE 'WOULD_APPLY' END
 FROM (VALUES ('000019_create_polis_queue.sql'),('000023_create_delphi_foundation.sql'),
              ('000024_create_polis_queue_large_class.sql'),
              ('000027_create_sealed_job_graphs.sql')) p(migration) CROSS JOIN readiness
 UNION ALL
 SELECT migration, NULL::boolean, 'OUTSIDE_RELEASE'
 FROM (VALUES ('000020'),('000021'),('000025'),('000026')) p(migration)
)
SELECT migration, catalog_match, outcome FROM output ORDER BY migration;
ROLLBACK;
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = MIG/'report/first-deploy.sql'
    text = build()
    if args.check:
        assert output.read_text() == text, 'report is stale; regenerate and review'
        print('PASS: report matches all source predicates and release metadata')
    else:
        output.parent.mkdir(exist_ok=True)
        output.write_text(text)
        print(output)


if __name__ == '__main__':
    main()
