"""Reproducible cut-cadence experiments for replay schedule inference.

Four experiment families measure how well the exact posterior localizes
TRUE recompute cuts as a function of cut cadence, cadence randomness, and
vote-arrival burstiness. All runs are count-constrained
(``t_range = (T, T)`` — tick count known) and draw 200 exact posterior
samples:

- ``fixed``   — true cut exactly every N votes (committed port of the
  original scratch probe): regular arrivals (gap ~U(0.6, 1.4) x 5 s), the
  physical cut fires shortly after its slot's vote, and marks are
  regenerated by true Plackett-Luce routing with servable delay
  ``cut_time + compute``.
- ``poisson`` — segment lengths in VOTES ~ ``1 + Poisson(N - 1)`` (mean
  N), cuts placed sequentially; same regular arrivals. Inference gets
  ``compute = 0.7 * N * 5000 ms`` as a point estimate with jitter 0.5 and
  an explicit spacing floor (derivation in :func:`build_poisson`).
- ``time``    — inter-cut WALL TIMES ~ ``Gamma(shape=3, mean=N*5 s)``
  truncated below at ``0.25 * N * 5 s``; segments then contain variable
  vote counts (mapping derivations in :func:`build_time_sampled`).
- ``bursty``  — Markov-modulated arrivals (~100-vote bursts with 0.2-1 s
  gaps alternating with lulls of a handful of votes at 60-600 s gaps,
  mimicking the real ``vw`` regime), cuts time-sampled with mean spacing
  60 s. Long inter-vote gaps are forced cuts in the inference lattice, so
  the generator injects those forced slots into the truth (physics
  consistency; see :func:`build_bursty`).

Every generated truth is checked for soundness BEFORE inference
(:func:`check_truth_sound`):

(i)   every forced slot of the inference lattice is contained in the truth;
(ii)  consecutive true cuts are feasible under the min-spacing actually
      passed to inference (the DP's own feasibility predicate);
(iii) the count constraint brackets the true cut count.
"""

import math
from dataclasses import dataclass
from typing import Optional, Sequence

import numpy as np
from scipy.optimize import linear_sum_assignment

from polismath.replay.dp import PriorConfig, sample_schedules
from polismath.replay.physics import forced_slots
from polismath.replay.scan import infer_schedule
from polismath.replay.types import (
    CommentMeta,
    ReplayDataset,
    Schedule,
    VoteEvent,
)
from polismath.replay.weights import PrefixStats, era_a_weights, era_b_weights

# --- shared skeleton constants (match the original probe) -------------------
GAP_S = 5.0                 # mean inter-vote gap for regular arrivals
GAP_JITTER = (0.6, 1.4)     # arrival gap ~ U(0.6, 1.4) * GAP_S
N_VOTES = 1000
N_COMMENTS = 25
POLL_MS = 1000
CUT_LAG_MS = 500            # physical cut fires within [t_slot, t_slot + poll)
IDLE_LAMBDA_PER_S = 0.1

N_SAMPLES = 200
SAMPLE_SEED = 9

BURSTY_MEAN_CUT_MS = 60_000.0

FAMILIES = ("fixed", "poisson", "time", "bursty")
GRID_NS = (5, 10, 50)
GRID_SEEDS = (0, 1, 2)
GRID_ERAS = ("B", "A")

_SIGN_VALUES = (1, -1, 0)
_SIGN_PROBS = (0.60, 0.25, 0.15)


class SoundnessError(ValueError):
    """The generated truth would be excluded by the inference config."""


@dataclass
class CadenceCase:
    """A generated dataset with its ground-truth schedule and inference config."""

    family: str
    era: str
    N: Optional[int]        # None for bursty (single config per era)
    seed: int
    ds: ReplayDataset
    truth: Schedule
    infer_kwargs: dict      # keyword args forwarded to infer_schedule
    config: dict            # provenance recorded into the results JSON


# --- arrival-time skeletons ---------------------------------------------------

def _regular_times(rng: np.random.Generator, n: int) -> np.ndarray:
    """Regular arrivals with mild jitter (no long gaps -> no forced cuts)."""
    gaps = rng.uniform(GAP_JITTER[0] * GAP_S, GAP_JITTER[1] * GAP_S, size=n)
    return (np.cumsum(gaps) * 1000.0).astype(np.int64)


def _bursty_times(rng: np.random.Generator, n: int) -> np.ndarray:
    """Markov-modulated arrivals: ~100-vote bursts alternating with lulls."""
    times: list[float] = []
    t = 0.0
    burst = True
    while len(times) < n:
        if burst:
            length, lo, hi = int(rng.uniform(80, 120)), 0.2, 1.0
        else:
            length, lo, hi = int(rng.uniform(2, 6)), 60.0, 600.0
        for _ in range(length):
            t += float(rng.uniform(lo, hi))
            times.append(t)
            if len(times) >= n:
                break
        burst = not burst
    return (np.array(times) * 1000.0).astype(np.int64)


def _make_comments(
    rng: np.random.Generator, t_last_ms: int, n_comments: int = N_COMMENTS
) -> tuple[dict[int, int], dict[int, CommentMeta]]:
    """First 5 comments exist from t=0; the rest appear during the first 60%."""
    created = {
        c: 0 if c < 5 else int(rng.uniform(0, t_last_ms * 0.6))
        for c in range(n_comments)
    }
    comments = {c: CommentMeta(tid=c, created_ms=created[c]) for c in created}
    return created, comments


# --- true mark generation (Plackett-Luce routing under the era weights) ------

def _route_votes(
    rng: np.random.Generator,
    t_ms: np.ndarray,
    cut_slots: Sequence[int],
    compute_ms: int,
    era: str,
    created: dict[int, int],
) -> list[tuple[int, int, int, int]]:
    """Regenerate marks by true PL routing with servable delay.

    A cut at slot ``s`` fires at ``t_s + CUT_LAG_MS`` (first poll after the
    slot's vote); its recomputed weights become servable ``compute_ms``
    later. Votes in between are routed under the previous weights — the
    exact semantics the DP's emission delay models.
    """
    n = len(t_ms)
    n_comments = len(created)
    # Guaranteed capacity: by vote k at most n_ptpts * c_k (pid, tid) pairs
    # exist, where c_k = comments created by t_k. Size the pool against the
    # tightest prefix (for regular arrivals this reduces to ceil(n /
    # n_comments) + 10, the original probe's pool; bursty arrivals bind
    # earlier, during the first burst when only the seed comments exist).
    created_times = np.sort(np.fromiter(created.values(), dtype=np.int64))
    c_k = np.maximum(np.searchsorted(created_times, t_ms, side="right"), 1)
    n_ptpts = int(np.max(np.ceil(np.arange(1, n + 1) / c_k))) + 10
    cutset = set(int(s) for s in cut_slots)

    stats = PrefixStats.empty()
    active: dict[int, float] = {}
    pending_switch: list[tuple[int, dict]] = []
    voted: dict[int, set[int]] = {}
    raw: list[tuple[int, int, int, int]] = []

    for k in range(1, n + 1):
        t = int(t_ms[k - 1])
        while pending_switch and pending_switch[0][0] <= t:
            active = pending_switch.pop(0)[1]
        # a uniformly random participant among those with availability at t
        pid, avail = None, None
        for p in rng.permutation(n_ptpts):
            a = sorted(
                c
                for c in range(n_comments)
                if created[c] <= t and c not in voted.get(int(p), set())
            )
            if a:
                pid, avail = int(p), a
                break
        if pid is None or avail is None:
            raise RuntimeError(
                "participant pool exhausted; raise n_ptpts / n_comments"
            )
        w = np.array([active.get(c, 1.0) for c in avail])
        tid = int(rng.choice(avail, p=w / w.sum()))
        sign = int(rng.choice(_SIGN_VALUES, p=_SIGN_PROBS))
        raw.append((t, pid, tid, sign))
        voted.setdefault(pid, set()).add(tid)
        stats.push(
            VoteEvent(k=k, t_ms=t, pid=pid, tid=tid, sign=sign, is_revote=False)
        )
        if k in cutset:
            wmap = (
                era_b_weights(stats)
                if era == "B"
                else era_a_weights(stats, {}, set())
            )
            pending_switch.append((t + CUT_LAG_MS + compute_ms, dict(wmap)))
    return raw


# --- cut-cadence samplers -----------------------------------------------------

def _time_sampled_cut_slots(
    rng: np.random.Generator,
    t_ms: np.ndarray,
    mean_ms: float,
    floor_ms: float,
    shape: float = 3.0,
) -> tuple[int, ...]:
    """Inter-cut wall times ~ Gamma(shape, mean=mean_ms) truncated at floor_ms.

    Each cut wall time maps to its slot (#votes at or before it). Cuts that
    ingest no new votes (same slot as the previous cut, or before the first
    vote) are dropped — a worker only recomputes when votes are pending —
    as are cuts at/after the last vote.
    """
    scale = mean_ms / shape
    slots: list[int] = []
    c = 0.0
    last = 0
    t_last = float(t_ms[-1])
    while True:
        tau = float(rng.gamma(shape, scale))
        while tau < floor_ms:  # truncation by resampling
            tau = float(rng.gamma(shape, scale))
        c += tau
        if c >= t_last:
            break
        s = int(np.searchsorted(t_ms, c, side="right"))
        if last < s < len(t_ms):
            slots.append(s)
            last = s
    return tuple(slots)


# --- experiment families --------------------------------------------------------

def build_fixed(era: str, N: int, seed: int, n_votes: int = N_VOTES) -> CadenceCase:
    """True cut exactly every N votes (the reference probe, committed)."""
    rng = np.random.default_rng(seed)
    t_ms = _regular_times(rng, n_votes)
    created, comments = _make_comments(rng, int(t_ms[-1]))
    truth = tuple(range(N, n_votes, N))
    compute_ms = int(0.7 * N * GAP_S * 1000.0)  # worker busy < inter-cut spacing
    raw = _route_votes(rng, t_ms, truth, compute_ms, era, created)
    ds = ReplayDataset.build(raw, comments=comments)
    infer_kwargs = dict(
        poll_interval_ms=POLL_MS,
        compute_ms=compute_ms,
        compute_jitter=0.3,
        idle_lambda_per_s=IDLE_LAMBDA_PER_S,
    )
    return CadenceCase(
        family="fixed", era=era, N=N, seed=seed, ds=ds, truth=truth,
        infer_kwargs=infer_kwargs,
        config=dict(
            n_votes=n_votes, gap_s=GAP_S, n_comments=N_COMMENTS,
            compute_ms=compute_ms, compute_jitter=0.3,
            min_spacing_ms=int((1.0 - 0.3) * compute_ms),
            idle_lambda_per_s=IDLE_LAMBDA_PER_S,
        ),
    )


def build_poisson(era: str, N: int, seed: int, n_votes: int = N_VOTES) -> CadenceCase:
    """Poisson-count cadence: segment lengths (votes) ~ 1 + Poisson(N - 1)."""
    rng = np.random.default_rng(seed)
    t_ms = _regular_times(rng, n_votes)
    created, comments = _make_comments(rng, int(t_ms[-1]))
    cuts: list[int] = []
    s = 0
    while True:
        s += 1 + int(rng.poisson(N - 1))
        if s >= n_votes:
            break
        cuts.append(s)
    truth = tuple(cuts)
    compute_ms = int(0.7 * N * GAP_S * 1000.0)  # point estimate; cadence random
    # Spacing-floor mapping: adjacent true cuts can be one vote apart
    # (L_j >= 1). For consecutive cuts a < b the DP feasibility predicate
    # reads t_{b+1} - t_a, which for b = a + 1 spans exactly two inter-vote
    # gaps >= 2 * 0.6 * GAP_S = 6.0 s (the generator's support minimum).
    # The compute-derived default (1 - jitter) * compute = 1.75 * N s
    # exceeds 6 s for N >= 4 and would exclude the truth, so we pass an
    # explicit floor just under the 2-gap support minimum.
    min_spacing_ms = int(2 * GAP_JITTER[0] * GAP_S * 1000.0) - 500  # 5500
    infer_kwargs = dict(
        poll_interval_ms=POLL_MS,
        compute_ms=compute_ms,
        compute_jitter=0.5,  # wider than fixed: cadence is random
        min_spacing_ms=min_spacing_ms,
        idle_lambda_per_s=IDLE_LAMBDA_PER_S,
    )
    raw = _route_votes(rng, t_ms, truth, compute_ms, era, created)
    return CadenceCase(
        family="poisson", era=era, N=N, seed=seed,
        ds=ReplayDataset.build(raw, comments=comments),
        truth=truth, infer_kwargs=infer_kwargs,
        config=dict(
            n_votes=n_votes, gap_s=GAP_S, n_comments=N_COMMENTS,
            segment_law=f"1 + Poisson({N - 1})",
            compute_ms=compute_ms, compute_jitter=0.5,
            min_spacing_ms=min_spacing_ms,
            idle_lambda_per_s=IDLE_LAMBDA_PER_S,
        ),
    )


def build_time_sampled(
    era: str, N: int, seed: int, n_votes: int = N_VOTES
) -> CadenceCase:
    """Time-sampled cadence: inter-cut wall times ~ truncated Gamma."""
    rng = np.random.default_rng(seed)
    t_ms = _regular_times(rng, n_votes)
    created, comments = _make_comments(rng, int(t_ms[-1]))
    mean_ms = N * GAP_S * 1000.0
    floor_ms = 0.25 * mean_ms
    truth = _time_sampled_cut_slots(rng, t_ms, mean_ms, floor_ms)
    compute_ms = int(0.7 * mean_ms)  # renewal/compute point estimate
    # Config mapping (derivations):
    # - min_spacing: true inter-cut wall times are >= floor_ms by
    #   construction, and the DP predicate t_{b+1} - t_a upper-bounds the
    #   realized wall spacing (t_a <= cut_j < cut_{j+1} < t_{b+1}), so any
    #   min_spacing < floor_ms is sound. We keep a 0.2 * mean safety
    #   margin: min_spacing = floor - 0.2 * mean = 0.05 * mean.
    # - compute_jitter: the scan-level default spacing is
    #   (1 - j) * compute; requiring (1 - j) * compute <= floor gives
    #   j >= 1 - floor/compute = 1 - 0.25/0.7 = 9/14 ~= 0.643 -> j = 0.65.
    #   min_spacing is passed explicitly anyway; the jitter's remaining
    #   role is the renewal ready-time (1 + j) * compute in the soft idle
    #   prior.
    min_spacing_ms = int(floor_ms - 0.2 * mean_ms)
    infer_kwargs = dict(
        poll_interval_ms=POLL_MS,
        compute_ms=compute_ms,
        compute_jitter=0.65,
        min_spacing_ms=min_spacing_ms,
        idle_lambda_per_s=IDLE_LAMBDA_PER_S,
    )
    raw = _route_votes(rng, t_ms, truth, compute_ms, era, created)
    return CadenceCase(
        family="time", era=era, N=N, seed=seed,
        ds=ReplayDataset.build(raw, comments=comments), truth=truth,
        infer_kwargs=infer_kwargs,
        config=dict(
            n_votes=n_votes, gap_s=GAP_S, n_comments=N_COMMENTS,
            cut_law=f"Gamma(shape=3, mean={mean_ms:.0f} ms) trunc >= {floor_ms:.0f} ms",
            compute_ms=compute_ms, compute_jitter=0.65,
            min_spacing_ms=min_spacing_ms,
            idle_lambda_per_s=IDLE_LAMBDA_PER_S,
        ),
    )


def build_bursty(
    era: str,
    seed: int,
    n_votes: int = N_VOTES,
    mean_cut_ms: float = BURSTY_MEAN_CUT_MS,
) -> CadenceCase:
    """Bursty arrivals x time-sampled cuts (the real ``vw`` regime)."""
    rng = np.random.default_rng(seed)
    t_ms = _bursty_times(rng, n_votes)
    created, comments = _make_comments(rng, int(t_ms[-1]))
    floor_ms = 0.25 * mean_cut_ms
    compute_ms = int(0.7 * mean_cut_ms)
    sampled = _time_sampled_cut_slots(rng, t_ms, mean_cut_ms, floor_ms)
    # Physics consistency: any inter-vote gap > poll + compute is a FORCED
    # slot in the inference lattice — an up worker with pending votes must
    # have recomputed during the gap. Purely time-sampled cuts would leave
    # some forced slots outside the truth (soundness check (i) rejects
    # that), so inject them. Injection cannot break check (ii): for any
    # neighbour pair involving a forced slot, the DP spacing t_{b+1} - t_a
    # includes the forcing gap itself (> poll + compute >> min_spacing).
    forced = {
        i + 1
        for i in range(len(t_ms) - 1)
        if t_ms[i + 1] - t_ms[i] > POLL_MS + compute_ms
    }
    truth = tuple(sorted(set(sampled) | forced))
    # Same mapping derivations as build_time_sampled with mean = 60 s:
    # floor = 15 s, compute = 42 s, j >= 1 - 0.25/0.7 -> 0.65,
    # min_spacing = floor - 0.2 * mean = 3 s.
    min_spacing_ms = int(floor_ms - 0.2 * mean_cut_ms)
    infer_kwargs = dict(
        poll_interval_ms=POLL_MS,
        compute_ms=compute_ms,
        compute_jitter=0.65,
        min_spacing_ms=min_spacing_ms,
        idle_lambda_per_s=IDLE_LAMBDA_PER_S,
    )
    raw = _route_votes(rng, t_ms, truth, compute_ms, era, created)
    return CadenceCase(
        family="bursty", era=era, N=None, seed=seed,
        ds=ReplayDataset.build(raw, comments=comments), truth=truth,
        infer_kwargs=infer_kwargs,
        config=dict(
            n_votes=n_votes, arrivals="bursty (U(0.2,1.0)s x ~100 | U(60,600)s x 2-5)",
            cut_law=f"Gamma(shape=3, mean={mean_cut_ms:.0f} ms) trunc >= {floor_ms:.0f} ms",
            n_comments=N_COMMENTS, compute_ms=compute_ms, compute_jitter=0.65,
            min_spacing_ms=min_spacing_ms, idle_lambda_per_s=IDLE_LAMBDA_PER_S,
            n_forced_slots=len(forced),
        ),
    )


def build_case(
    family: str,
    era: str,
    N: Optional[int],
    seed: int,
    n_votes: int = N_VOTES,
) -> CadenceCase:
    if family == "fixed":
        return build_fixed(era, int(N), seed, n_votes=n_votes)  # type: ignore[arg-type]
    if family == "poisson":
        return build_poisson(era, int(N), seed, n_votes=n_votes)  # type: ignore[arg-type]
    if family == "time":
        return build_time_sampled(era, int(N), seed, n_votes=n_votes)  # type: ignore[arg-type]
    if family == "bursty":
        return build_bursty(era, seed, n_votes=n_votes)
    raise ValueError(f"unknown experiment family {family!r}")


# --- soundness ------------------------------------------------------------------

def resolved_min_spacing_ms(infer_kwargs: dict) -> int:
    """The hard spacing the DP will actually use (mirrors infer_schedule)."""
    explicit = infer_kwargs.get("min_spacing_ms")
    if explicit is not None:
        return int(explicit)
    jitter = infer_kwargs.get("compute_jitter", 0.3)
    return int((1.0 - jitter) * infer_kwargs["compute_ms"])


def check_truth_sound(
    case: CadenceCase, t_range: Optional[tuple[int, int]] = None
) -> None:
    """Raise SoundnessError if the truth would be excluded by inference.

    (i) forced lattice slots must be in the truth; (ii) consecutive true
    cuts must pass the DP's min-spacing feasibility predicate; (iii) the
    count constraint must bracket the true count.
    """
    ds, truth = case.ds, case.truth
    if not truth:
        raise SoundnessError(f"{case.family}: empty truth schedule")
    ds.validate_schedule(truth)

    forced = forced_slots(
        ds,
        poll_interval_ms=case.infer_kwargs["poll_interval_ms"],
        compute_ms=case.infer_kwargs["compute_ms"],
    )
    stray = forced - set(truth)
    if stray:
        raise SoundnessError(
            f"{case.family}: forced slots not in truth: {sorted(stray)[:5]}"
            f" ({len(stray)} total)"
        )

    min_spacing = resolved_min_spacing_ms(case.infer_kwargs)
    t = [v.t_ms for v in ds.votes]
    for a, b in zip(truth, truth[1:]):
        if b < ds.n and t[b] - t[a - 1] <= min_spacing:
            raise SoundnessError(
                f"{case.family}: true cuts ({a}, {b}) infeasible under "
                f"min_spacing_ms={min_spacing} "
                f"(max wall spacing {t[b] - t[a - 1]} ms)"
            )

    t_range = t_range or (len(truth), len(truth))
    if not t_range[0] <= len(truth) <= t_range[1]:
        raise SoundnessError(
            f"{case.family}: t_range {t_range} does not bracket "
            f"{len(truth)} true cuts"
        )


# --- metrics ----------------------------------------------------------------------

def _slot_times_ms(t_arr: np.ndarray, slots) -> np.ndarray:
    """Wall time of (possibly fractional) 1-based slots via interpolation."""
    return np.interp(
        np.asarray(slots, dtype=float),
        np.arange(1, len(t_arr) + 1, dtype=float),
        t_arr,
    )


def localization_and_coverage(
    samples: list[Schedule],
    truth: Schedule,
    t_arr: np.ndarray,
    cov_votes: int = 3,
    cov_secs: float = 10.0,
) -> dict:
    """Per-true-cut posterior localization and coverage, votes and seconds.

    For each true cut: the median over samples of the nearest-sampled-cut
    distance (in votes; separately in seconds via the dataset's vote
    times), and the fraction of samples with a cut within the coverage
    window. Aggregated as median and p90 across true cuts (localization)
    and mean across true cuts (coverage).
    """
    arrs = [np.asarray(sch) for sch in samples if sch]
    tarrs = [t_arr[a - 1] for a in arrs]
    truth_t = t_arr[np.asarray(truth) - 1]
    per_v, per_s, hit_v, hit_s = [], [], [], []
    for tc, tt in zip(truth, truth_t):
        dv = np.array([np.abs(a - tc).min() for a in arrs], dtype=float)
        dsec = np.array([np.abs(ta - tt).min() for ta in tarrs]) / 1000.0
        per_v.append(float(np.median(dv)))
        per_s.append(float(np.median(dsec)))
        hit_v.append(float(np.mean(dv <= cov_votes)))
        hit_s.append(float(np.mean(dsec <= cov_secs)))
    return {
        "loc_med_votes": float(np.median(per_v)),
        "loc_p90_votes": float(np.percentile(per_v, 90)),
        "loc_med_s": float(np.median(per_s)),
        "loc_p90_s": float(np.percentile(per_s, 90)),
        "cov_3votes": float(np.mean(hit_v)),
        "cov_10s": float(np.mean(hit_s)),
    }


def matched_displacement(
    est: Sequence[float], truth: Schedule, t_arr: np.ndarray
) -> tuple[float, float]:
    """Median displacement under optimal 1-1 assignment, votes and seconds.

    Two independent matchings (scipy linear_sum_assignment): one on
    absolute slot differences, one on absolute wall-time differences.
    """
    a = np.sort(np.asarray(est, dtype=float))
    b = np.sort(np.asarray(truth, dtype=float))
    if a.size == 0 or b.size == 0:
        return math.nan, math.nan
    cost_v = np.abs(a[:, None] - b[None, :])
    r, c = linear_sum_assignment(cost_v)
    med_v = float(np.median(cost_v[r, c]))
    ta, tb = _slot_times_ms(t_arr, a), _slot_times_ms(t_arr, b)
    cost_s = np.abs(ta[:, None] - tb[None, :]) / 1000.0
    r, c = linear_sum_assignment(cost_s)
    med_s = float(np.median(cost_s[r, c]))
    return med_v, med_s


def per_index_median(samples: list[Schedule]) -> tuple[np.ndarray, bool]:
    """Coordinate-wise median schedule over count-constrained samples.

    Requires all samples to have the same cut count (t_range = (T, T)).
    Coordinate-wise medians of sorted vectors are monotone nondecreasing
    by construction; we still verify and sort defensively, reporting
    whether sorting was ever needed.
    """
    lens = {len(s) for s in samples}
    if len(lens) != 1:
        raise ValueError(
            f"per-index median needs equal-length samples, got lengths {sorted(lens)}"
        )
    arr = np.asarray(samples, dtype=float)
    med = np.median(arr, axis=0)
    sort_needed = bool(np.any(np.diff(med) < 0))
    if sort_needed:
        med = np.sort(med)
    return med, sort_needed


# --- runner -------------------------------------------------------------------------

def run_case(
    case: CadenceCase,
    n_samples: int = N_SAMPLES,
    sample_seed: int = SAMPLE_SEED,
) -> dict:
    """Soundness-check, infer, sample, and compute all metrics for one case."""
    truth = case.truth
    t_range = (len(truth), len(truth))
    check_truth_sound(case, t_range)

    res = infer_schedule(
        case.ds,
        era=case.era,
        prior=PriorConfig(log_gamma=0.0, t_range=t_range),
        **case.infer_kwargs,
    )
    samples = sample_schedules(res.state, n_samples, np.random.default_rng(sample_seed))
    t_arr = np.array([v.t_ms for v in case.ds.votes], dtype=float)

    out = {
        "family": case.family,
        "era": case.era,
        "N": case.N,
        "seed": case.seed,
        "n_votes": case.ds.n,
        "n_cuts": len(truth),
        "n_samples": n_samples,
    }
    out.update(localization_and_coverage(samples, truth, t_arr))

    med_sched, sort_needed = per_index_median(samples)
    for name, est in (
        ("map", res.dp.map_schedule),
        ("median", med_sched),
        ("sample1", samples[0]),
    ):
        v, s = matched_displacement(est, truth, t_arr)
        out[f"disp_{name}_votes"] = v
        out[f"disp_{name}_s"] = s
    out["median_sort_needed"] = sort_needed

    out["map_mass"] = float(np.exp(res.dp.map_logpost - res.dp.log_Z))
    out["distinct_schedules"] = len({tuple(s) for s in samples})
    out["config"] = dict(case.config)
    return out


def grid_specs(
    exp: str = "all",
    eras: Sequence[str] = GRID_ERAS,
    ns: Sequence[int] = GRID_NS,
    seeds: Sequence[int] = GRID_SEEDS,
    n_votes: int = N_VOTES,
) -> list[dict]:
    """The experiment grid: era x N x seed per family (bursty: one config)."""
    families = FAMILIES if exp == "all" else (exp,)
    if not set(families) <= set(FAMILIES):
        raise ValueError(f"unknown experiment {exp!r}")
    specs = []
    for family in families:
        for era in eras:
            for N in (None,) if family == "bursty" else tuple(ns):
                for seed in seeds:
                    specs.append(
                        dict(family=family, era=era, N=N, seed=seed, n_votes=n_votes)
                    )
    return specs


AGG_KEYS = (
    "n_cuts",
    "loc_med_votes", "loc_p90_votes", "loc_med_s", "loc_p90_s",
    "cov_3votes", "cov_10s",
    "disp_map_votes", "disp_map_s",
    "disp_median_votes", "disp_median_s",
    "disp_sample1_votes", "disp_sample1_s",
    "map_mass", "distinct_schedules",
)


def aggregate(runs: list[dict]) -> list[dict]:
    """Median across seeds per (family, era, N) cell."""
    groups: dict[tuple, list[dict]] = {}
    for r in runs:
        groups.setdefault((r["family"], r["era"], r["N"]), []).append(r)
    out = []
    for (family, era, N), rs in sorted(
        groups.items(),
        key=lambda kv: (
            FAMILIES.index(kv[0][0]),
            GRID_ERAS.index(kv[0][1]),
            kv[0][2] or 0,
        ),
    ):
        agg: dict = {"family": family, "era": era, "N": N, "n_runs": len(rs)}
        for key in AGG_KEYS:
            agg[key] = float(np.median([r[key] for r in rs]))
        agg["median_sort_needed_any"] = any(r["median_sort_needed"] for r in rs)
        out.append(agg)
    return out
